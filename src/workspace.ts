import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { profileNameFromFilename } from "./names.ts";

/** Directory names skipped while walking for consumers. */
const SKIP_DIR_NAMES = new Set([
  "node_modules",
  ".git",
  "dist",
  "build",
  "coverage",
  "out",
  ".next",
  ".nuxt",
  ".output",
  ".turbo",
  ".cache",
  ".vercel",
  ".pnpm-store",
]);

const shouldSkipDir = (name: string): boolean =>
  SKIP_DIR_NAMES.has(name) || (name.startsWith(".") && name !== ".");

/**
 * Absolute paths of env consumers: any non-root directory that owns `.env.example`.
 * Walks from `root`, skipping junk dirs. Does not recurse into a consumer once found.
 */
export const listConsumerDirs = (root: string): string[] => {
  const found: string[] = [];

  const walk = (dir: string): void => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }

    if (dir !== root && existsSync(join(dir, ".env.example"))) {
      found.push(dir);
      return;
    }

    for (const entry of entries) {
      if (!entry.isDirectory()) continue;
      if (shouldSkipDir(entry.name)) continue;
      walk(join(dir, entry.name));
    }
  };

  walk(root);
  return found.sort();
};

/**
 * Profile slugs that already exist on disk (root and/or under consumers).
 * Does not invent profiles from .env.example alone.
 */
export const listExistingProfileNames = (root: string): string[] => {
  const names = new Set<string>();

  const collectFromDir = (dir: string) => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isFile()) continue;
      const name = profileNameFromFilename(entry.name);
      if (name) names.add(name);
    }
  };

  collectFromDir(root);
  for (const dir of listConsumerDirs(root)) {
    collectFromDir(dir);
  }

  return [...names].sort();
};

/** Forward-slash path of a consumer relative to the monorepo root. */
export const consumerRelPath = (root: string, dir: string): string =>
  relative(root, dir).split(/[/\\]/).join("/");

/** Write a generated .env with the standard "do not edit" header. */
export const writeGeneratedEnv = (
  outPath: string,
  body: string,
  name: string,
  sourceLabel: string
): void => {
  const header = `# Generated by \`pnpm envmng set ${name}\` from ${sourceLabel} — do not edit; change the template / central values and re-run.\n`;
  mkdirSync(resolve(outPath, ".."), { recursive: true });
  const content = body.startsWith("#") ? `${header}\n${body}` : `${header}\n${body}`;
  writeFileSync(outPath, content.endsWith("\n") ? content : `${content}\n`, "utf8");
};
